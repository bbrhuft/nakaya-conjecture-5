#!/usr/bin/env python3
"""Audit saved GP output and produce compact review artifacts; Python stdlib only."""
from pathlib import Path
import csv, json, re, collections, hashlib
from math import isqrt
ROOT = Path(__file__).resolve().parents[1]
R = ROOT / 'results'
def rows(name):
    with (R/name).open(newline='') as f: return list(csv.DictReader(f))
pairs=rows('pairs.csv'); levels=rows('levels.csv'); summary=rows('summary.csv'); exc=rows('exceptions.csv'); ordinary=rows('ordinary_ss.csv'); outside=rows('outside_scope.csv')
Ns=[int(x['N']) for x in levels]
primes=[int(x['p']) for x in ordinary]
assert all(p>=5 and all(p%d for d in range(2,isqrt(p)+1)) for p in primes)
assert len(primes)==len(set(primes))
expected={(N,p) for N in Ns for p in primes if p!=N}
keys=[(int(x['N']),int(x['p'])) for x in pairs]
assert len(keys)==len(set(keys)) and set(keys)==expected
assert all(x['status']=='PASS' and x['degree_rad']==x['Jordan_degree'] for x in pairs)
assert all(x['Legendre_equal']=='PASS' for x in ordinary)
exkeys={(int(x['N']),int(x['p'])) for x in exc}
assert len(exkeys)==len(exc)
assert exkeys=={k for k,x in zip(keys,pairs) if int(x['exception_flags'])>0}
assert all(x['status']=='PASS' for x in exc)
assert len(outside)==2*len(Ns)+sum(N>=5 for N in Ns)
for N in Ns:
    text=(R/f'factors_{N}.txt').read_text()
    records=re.findall(r'N=(\d+) p=(\d+) (\w+)\nactual=(.*?)\npredicted=(.*?)\nfirst_mismatch=(.*?)\n',text)
    assert len(records)==sum(k[0]==N for k in expected)
    assert {(int(n),int(p)) for n,p,*_ in records}=={k for k in expected if k[0]==N}
    assert all(status=='PASS' and a==b and not mismatch for n,p,status,a,b,mismatch in records)
    sr=next(x for x in summary if int(x['N'])==N)
    assert int(sr['tested'])==len(records) and int(sr['failed'])==0
    assert int(sr['exceptional'])==sum(k[0]==N for k in exkeys)
with (R/'status_matrix.csv').open('w',newline='') as f:
    w=csv.writer(f);w.writerow(['N']+primes)
    for N in Ns:w.writerow([N]+['OUTSIDE' if N==p else 'PASS' for p in primes])
with (R/'correction_polynomials.txt').open('w') as f:
    f.write('Exact integer polynomials, variable T = Nakaya Y. Generated by q-expansions.\n\n')
    for N in Ns:
        f.write(f'N={N}\n')
        for line in (R/f'integer_factors_{N}.txt').read_text().splitlines():
            if line.startswith(('U0=','U1728=','A=','B=','E=','disc E=')):f.write(line+'\n')
        f.write('\n')
info={'status':'PASS','permitted_pairs':len(pairs),'odd_level_pairs':sum(int(x['N'])!=2 for x in pairs),'levels':Ns,'primes':len(primes),'largest_prime':max(primes),'flagged_pairs':len(exc),'correction_collision_pairs':sum(x['flags']!='disc_rad_D' for x in exc),'plane_discriminant_only_pairs':sum(x['flags']=='disc_rad_D' for x in exc),'flag_counts':dict(collections.Counter(t for x in exc for t in x['flags'].split(';'))),'max_multiplicity':max(int(x['max_multiplicity']) for x in pairs),'outside_pairs':len(outside),'formal_diagonal_failures':sum(x['formal_diagonal_check']=='FAIL_SQUARED_FORM' for x in outside),'scope':'Saved-output structural audit, not a second number-theoretic implementation.'}
(R/'audit.json').write_text(json.dumps(info,indent=2)+'\n')
# Report tables.
lines=[r'\begin{center}',r'\begin{tabular}{rrrrrrr}',r'\toprule',r'$N$ & Pairs & Failures & Flagged & $\deg A_N$ & $\deg B_N$ & $\deg E_N$\\',r'\midrule']
for x in summary:
    l=next(l for l in levels if l['N']==x['N'])
    lines.append(' & '.join(x[k] for k in ['N','tested','failed','exceptional'])+' & '+' & '.join(l[k] for k in ['degree_A','degree_B','degree_E'])+r'\\')
lines += [r'\midrule',f'Total & {len(pairs)} & 0 & {len(exc)} & & &'+r'\\',r'\bottomrule',r'\end{tabular}',r'\end{center}',f'The fourteen odd levels account for {info["odd_level_pairs"]:,} pairs; level 2 contributes {sum(int(x["N"])==2 for x in pairs)}.']
(ROOT/'report/computed_summary.tex').write_text('\n'.join(lines)+'\n')
lines=[r'All entries below pass. A prime is listed if any certificate described in Section 4 vanishes modulo that prime.',r'\begin{longtable}{rp{.86\linewidth}}',r'\toprule $N$ & Flagged primes $5\le p\le400$, $p\ne N$\\\midrule\endhead']
for N in Ns:
    lines.append(str(N)+' & '+', '.join(x['p'] for x in exc if int(x['N'])==N)+r'\\\addlinespace')
lines += [r'\bottomrule\end{longtable}']
(ROOT/'report/exception_table.tex').write_text('\n'.join(lines)+'\n')
print(json.dumps(info,indent=2))
